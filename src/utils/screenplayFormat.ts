/**
 * 编剧工作台的正文行式。
 * 集标题仍由「##」分开，场次写在正文里，不能再使用 # / ##，否则会被当成新的一集。
 */

export const SCREENPLAY_FORMAT_RULES = `【正文格式】这一集只输出场次正文。不要大纲、人物小传、创作说明，不要 Markdown 标题、加粗、列表或代码块。其他技能里的「### 场号」「■ 动作」「场次任务」「**人物：**」都不要用，以下面的行式为准。

每一场按这个顺序，一行一件事，场内不要空行，场与场之间空一行：

场景 1 · 城郊乱葬岗 · 夜 · 外
雨下了整夜。土坑里堆着没人认领的尸首，腐叶被风翻起，露出半只青白的手。
（本场 412 字 · 预计 48 秒 · 4 镜）
林遥从坑底坐起来。雨水顺着额发往下淌，他低头看自己的手——指甲缝里全是黑泥，指尖却泛着淡淡的青。
旁白：三年前他只是市三院一个连夜班都排不上的实习医生。
林遥（哑声）：这不对……我的手。
老陈举着灯从坡上下来，灯光扫过坑底，照见他一身泥，也照见他手背上那道新鲜的划口。
老陈：哟，醒了？
林遥：老人家，这是什么地方？
老陈：城郊乱葬岗。你从哪儿摔下来的？
林遥张了张嘴。记忆像被雨冲掉的粉笔字，他只记得自己在一间地下实验室里，给一个孩子做手术。
老陈（凑近，压低声音）：你手上那味儿……是尸油。
林遥猛地攥紧手，指节发白。坑底那半只青白的手，在他眼前晃了一下。
出场　林遥、老陈　道具　马灯、化肥袋　环境音　雨声、远处犬吠

行式要求：
- 场次标题单独一行：场景 N · 地点 · 日或夜 · 内或外。N 从 1 递增。不要写成「### 1-1」或「场景N｜标题」。
- 动作用现在时，只写观众能看见或听见的短句，单独成行。不要写景别、运镜和场次任务。
- 开场动作后面写一行：（本场 字数 · 预计 秒数 · 镜数）。字数按这一场的汉字粗算，秒数按短剧节奏估，镜数按能拍出来的动作节拍估。
- 旁白单独一行，写成「旁白：……」。不要加 >。
- 对白单独一行，写成「角色：台词」或「角色（语气）：台词」。语气放在名字后面、冒号前面。
- 每场最后一行：出场　人物用顿号隔开　道具　物件　环境音　声音。三项之间用全角空格。没有的项写「无」。
- 上面那段只示范行式，不要照抄这段剧情。续写或改写时保留已有情节和对白原意，并整理成这个格式。
- 不要输出集标题。集名已经在左侧。`

const SCENE_LINE = /^场景\s*[0-9０-９]/

/** 把模型偶尔带上的标题符号收成编辑器能上色的场次行。 */
export function normalizeScreenplayBody(raw: string) {
  let text = String(raw || '').replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n').trim()
  text = text.replace(/^```(?:markdown|md|text)?\s*/i, '').replace(/\s*```$/, '').trim()
  const lines = text.split('\n').map((line) => {
    let next = line.replace(/^#{1,6}\s+/, '')
    next = next.replace(/^\*\*([^*]+)\*\*/, '$1')
    next = next.replace(/^\*\s*(?=（|\()/, '')
    next = next.replace(/^>\s*(?=旁白|画外音|OS|os)/, '')
    const spoken = next.match(/^(\s*)([\u4e00-\u9fa5A-Za-z0-9·.]{1,12})[：:]((?:（[^）]{1,40}）|\([^)]{1,40}\)))(?![：:])(.*)$/)
    if (spoken && !/^(?:旁白|画外音|OS|os|出场|道具|环境音|场景)$/.test(spoken[2])) {
      next = `${spoken[1]}${spoken[2]}${spoken[3]}：${spoken[4].replace(/^\s+/, '')}`
    }
    return next
  })
  const firstScene = lines.findIndex((line) => SCENE_LINE.test(line.trim()))
  const body = (firstScene > 0 ? lines.slice(firstScene) : lines).join('\n')
  return body.replace(/\n{3,}/g, '\n\n').trim()
}
