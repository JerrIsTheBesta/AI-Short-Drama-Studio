export const SCRIPT_REFERENCE_OPTIONS = [
  { value: 'auto', label: '自动匹配' },
  { value: 'off', label: '不使用' },
  ...cards.map((card) => ({ value: card.name, label: card.name }))
]

export function normalizeScriptReference(value: unknown): string {
  return SCRIPT_REFERENCE_OPTIONS.some((item) => item.value === value) ? String(value) : 'auto'
}

export function scriptReferenceBrief(selection: string, ...parts: Array<string | undefined>): string {
  const selected = normalizeScriptReference(selection)
  if (selected === 'off') return ''
  const text = parts.filter(Boolean).join('\n')
  const matched = cards.map((card, index) => ({ card, index, score: card.words.reduce((n, word) => n + (text.includes(word) ? 1 : 0), 0) }))
    .filter((item) => selected === 'auto' ? item.score > 0 : item.card.name === selected)
    .sort((a, b) => b.score - a.score || a.index - b.index)
    .slice(0, 3)
  const specific = matched.map(({ card }) => `【${card.name}】${card.body}\n原创对白示例（只观察接话方式，不得套用具体台词或情节）：${dialogueExamples[card.name]}`).join('\n')
  return `【内置短剧写作参考】仅参考叙事技法，按用户题材、风格和要求灵活运用，不得套用固定情节。\n重点写自然、能说出口的中文对白：每个人有不同身份、情绪和说话习惯；先想清楚每人想达到什么，再让回答针对对方刚说的话，有时可回避、反问、打断、改口或停顿，依据人物和场景选择，不要每句都套用。允许省略双方已经知道的信息，不让人物互相解释背景或讲道理。穿插有意义的动作和反应，避免连续整齐对仗、金句和旁白说教。重要对手戏有实质来往，不用一句话概括冲突；同时遵守用户给出的时长和对白要求。场景写清人物的位置、动作和局面变化，悬念依故事需要安排。\n${specific}\n原创人物、对白与事件，不复用参考作品或示例的独特表达和具体桥段。用户指定的剧情、已有对白和续写边界优先。`
}
